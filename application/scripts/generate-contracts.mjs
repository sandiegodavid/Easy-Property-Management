import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { format, resolveConfig } from "prettier";
import { workflowContracts, workflowDispatch } from "./workflow-contracts.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const python =
  process.env.EPM_PYTHON ??
  (existsSync(`${root}.venv/bin/python`)
    ? `${root}.venv/bin/python`
    : `${root}../.venv/easy-property-management/bin/python`);
const schema = execFileSync(python, ["scripts/export_openapi.py"], {
  cwd: root,
  env: { ...process.env, PYTHONPATH: `${root}apps/server` },
  encoding: "utf8",
  maxBuffer: 32 * 1024 * 1024,
});
const types = `// Generated by npm run contracts:generate. Do not edit.\n${astToString(await openapiTS(schema))}`;
const adminSchema = await format(
  execFileSync(python, ["scripts/export_admin_openapi.py"], {
    cwd: root,
    env: { ...process.env, PYTHONPATH: `${root}apps/server` },
    encoding: "utf8",
  }),
  { ...(await resolveConfig(`${root}packages/contracts/admin-openapi.json`)), parser: "json" },
);
const adminTypes = `// Generated by npm run contracts:generate. Do not edit.\n${astToString(await openapiTS(adminSchema))}`;
for (const [path, content] of [
  ["packages/contracts/openapi.json", schema],
  ["packages/contracts/src/generated/schema.ts", types],
  ["packages/contracts/admin-openapi.json", adminSchema],
  ["packages/contracts/src/generated/admin-schema.ts", adminTypes],
  ["packages/contracts/src/generated/workflows.json", workflowContracts(JSON.parse(schema))],
  ["packages/contracts/src/generated/workflow-dispatch.ts", workflowDispatch(JSON.parse(schema))],
]) {
  const destination = new URL(`../${path}`, import.meta.url);
  if (process.argv.includes("--check")) {
    if ((await readFile(destination, "utf8")) !== content) {
      throw new Error(`${path} is stale; run npm run contracts:generate and commit the result.`);
    }
  } else {
    await mkdir(new URL(".", destination), { recursive: true });
    await writeFile(destination, content);
  }
}
console.log("OpenAPI snapshot and TypeScript contracts are reproducible without a workspace.");
